    /// <summary>The number of projected instruments and matrix cells.</summary>
    private const int InstrumentCount = 40;

    /// <summary>The number of available feature cards and instruments per matrix row.</summary>
    private const int RowWidth = 10;

    /// <summary>The number of sector groups.</summary>
    private const int SectorCount = 5;

    /// <summary>The rate assigned when the view model is constructed.</summary>
    private const int DefaultRate = 10_000;

    /// <summary>The rate yielding one thousand raw events per step.</summary>
    private const int StepRate = 8_000;

    /// <summary>The raw event count generated by each step or low-rate burst.</summary>
    private const int RawFrameCount = 1_000;

    /// <summary>The number of pause toggles used to verify notifications.</summary>
    private const int ToggleCount = 3;

    /// <summary>The retained tape bound.</summary>
    private const int TapeLimit = 800;

    /// <summary>The largest indexed history after trimming whole frames.</summary>
    private const int IndexedLimit = 1_240;

    /// <summary>The diagnostic stream retention bound.</summary>
    private const int StreamLimit = 160;

    /// <summary>The number of bursts needed to cross both history bounds.</summary>
    private const int BurstCount = 35;

    /// <summary>Exposes the venue matrix, feature catalog and initially running commands.</summary>
    /// <returns>A task representing the asynchronous test.</returns>
    [Test]
    public async Task Constructor_InitialState_ExposesShowcase()
    {
        using var model = new MainWindowViewModel(new FixedTimeProvider());
        var running = model.IsRunning;
        var startText = model.StartPauseText;
        var canStep = model.StepCommand.CanExecute(null);
        model.StartPauseCommand.Execute(null);
        await Assert.That(running).IsTrue();
        await Assert.That(startText).IsEqualTo("Pause");
        await Assert.That(canStep).IsFalse();
        await Assert.That(model.MatrixCellCount).IsEqualTo(InstrumentCount);
        await Assert.That(Array.ConvertAll(ReadItems<MatrixRow>(model.MatrixRows), static row => row.Lane))
            .IsEquivalentTo(model.Venues);
        var cards = ReadItems<FeatureCard>(model.Features);
        await Assert.That(cards.Length).IsEqualTo(RowWidth);
        await Assert.That(Array.TrueForAll(cards, static card =>
            card.Name.Length > 0 && card.Category.Length > 0 && card.Description.Length > 0 && card.LiveUse.Length > 0)).IsTrue();
        await Assert.That(model.TargetRate).IsEqualTo(DefaultRate);
        await Assert.That(model.SelectedVenue).IsEqualTo("LSE");
        await Assert.That(model.SearchText).IsEqualTo(string.Empty);
        await Assert.That(model.OnlyAlerts).IsFalse();
    }

