    /// <summary>Projects one paused frame into all views, the price matrix and stream diagnostics.</summary>
    /// <returns>A task representing the asynchronous test.</returns>
    [Test]
    public async Task StepCommand_Paused_ProjectsMarketFrame()
    {
        using var model = CreatePausedModel();
        model.TargetRate = StepRate;
        model.StepCommand.Execute(null);
        DrainDispatcher();
        var tape = ReadItems<InstrumentSnapshot>(model.LiveTape);
        var rows = ReadItems<MatrixRow>(model.MatrixRows);
        var streams = ReadItems<StreamEvent>(model.StreamEvents);
        await Assert.That(tape.Length).IsEqualTo(InstrumentCount);
        await Assert.That(model.TotalEvents).IsEqualTo((long)RawFrameCount);
        await Assert.That(model.SourceCount).IsEqualTo(InstrumentCount);
        await Assert.That(model.VisibleCount).IsEqualTo(InstrumentCount);
        await Assert.That(model.ViewBacklogCount).IsEqualTo(0);
        await Assert.That(model.HotTickCount).IsEqualTo(RawFrameCount);
        await Assert.That(model.HotDictionaryCount).IsEqualTo(InstrumentCount);
        await Assert.That(model.QuaternaryListCount).IsEqualTo(InstrumentCount);
        await Assert.That(model.QuaternaryDictionaryCount).IsEqualTo(InstrumentCount);
        await Assert.That(model.ReactiveListVersion).IsGreaterThan(0L);
        await Assert.That(model.GenerationMilliseconds).IsGreaterThan(0D);
        await Assert.That(model.AllocatedKilobytesPerFrame).IsGreaterThanOrEqualTo(0D);
        var expectedAlerts = Array.FindAll(tape, static snapshot => snapshot.IsAlert);
        await Assert.That(model.AlertCount).IsEqualTo(expectedAlerts.Length);
        await Assert.That(model.Alerts).IsEquivalentTo(expectedAlerts);
        await Assert.That(model.SlowestUpdates).IsEquivalentTo(tape);
        for (var i = 1; i < model.SlowestUpdates.Count; i++)
        {
            await Assert.That(model.SlowestUpdates[i - 1].LatencyMilliseconds)
                .IsGreaterThanOrEqualTo(model.SlowestUpdates[i].LatencyMilliseconds);
        }

        await Assert.That(model.SectorGroups.Count).IsEqualTo(SectorCount);
        await Assert.That(model.IndexedVenueSnapshots.Count).IsEqualTo(RowWidth);
        await Assert.That(model.IndexedVenueDictionary.Count).IsEqualTo(RowWidth);
        await Assert.That(Array.Exists(streams, static item => item.Source == "Connect() ChangeSet" && item.Detail == "ChangeSet projection")).IsTrue();
        await Assert.That(Array.Exists(streams, static item => item.Detail == "Pooled batch notification")).IsTrue();
        await Assert.That(Array.Exists(streams, static item => item.Detail == "Single cache notification")).IsTrue();
        await Assert.That(Array.TrueForAll(streams, static item => item.Time == "12:34:56.000" && item.Count > 0)).IsTrue();
        for (var row = 0; row < rows.Length; row++)
        {
            var total = 0D;
            var minimum = double.MaxValue;
            var maximum = double.MinValue;
            for (var column = 0; column < RowWidth; column++)
            {
                var price = tape[(row * RowWidth) + column].Price;
                total += price;
                minimum = Math.Min(minimum, price);
                maximum = Math.Max(maximum, price);
            }

            await Assert.That(rows[row].Average).IsEqualTo(total / RowWidth);
            await Assert.That(rows[row].Minimum).IsEqualTo(minimum);
            await Assert.That(rows[row].Maximum).IsEqualTo(maximum);
            await Assert.That(rows[row].Values.Length).IsGreaterThan(0);
        }

        await Assert.That(model.LastOperation).IsEqualTo("Single projection frame generated from 1,000 events");
    }

    /// <summary>Matches symbols, sectors and venues case-insensitively and trims whitespace.</summary>
    /// <param name="search">The dynamic search query.</param>
    /// <param name="expected">The expected count within a complete instrument frame.</param>
    /// <returns>A task representing the asynchronous test.</returns>
    [Test]
    [Arguments(" rl01 ", 1)]
    [Arguments("technology", 8)]
    [Arguments("xnas", 10)]
    [Arguments("missing", 0)]
    [Arguments("", 40)]
    public async Task SearchText_Query_RebuildsDynamicView(string search, int expected)
    {
        using var model = CreatePausedModel();
        model.StepCommand.Execute(null);
        DrainDispatcher();
        model.SearchText = search;
        model.SearchText = search;
        DrainDispatcher();
        var resultCount = model.SearchResults.Count;
        model.OnlyAlerts = true;
        DrainDispatcher();
        var alerts = ReadItems<InstrumentSnapshot>(model.SearchResults);
        model.OnlyAlerts = false;
        DrainDispatcher();
        await Assert.That(resultCount).IsEqualTo(expected);
        await Assert.That(Array.TrueForAll(alerts, static snapshot => snapshot.IsAlert)).IsTrue();
        await Assert.That(model.SearchResults.Count).IsEqualTo(expected);
        await Assert.That(model.LastOperation).IsEqualTo("Dynamic view predicate updated");
    }

