    /// <summary>Publishes sampled throughput after continuous producer frames reach the dispatcher.</summary>
    /// <param name="cancellationToken">Stops the dispatcher frame if the test is cancelled.</param>
    /// <returns>A task representing the asynchronous test.</returns>
    [Test]
    [Timeout(10_000)]
    public async Task ContinuousProducer_MetricNotification_PublishesRates(CancellationToken cancellationToken)
    {
        using var model = new MainWindowViewModel();
        var frame = new DispatcherFrame();
        await using var cancellation = cancellationToken.Register(
            static state => ((DispatcherFrame)state!).Continue = false,
            frame);
        model.PropertyChanged += (_, args) =>
        {
            if (args.PropertyName != nameof(MainWindowViewModel.UiFramesPerSecond))
            {
                return;
            }

            frame.Continue = false;
        };
        Dispatcher.PushFrame(frame);
        var eventsPerSecond = model.EventsPerSecond;
        var framesPerSecond = model.UiFramesPerSecond;
        model.StartPauseCommand.Execute(null);
        await Assert.That(eventsPerSecond).IsGreaterThan(0D);
        await Assert.That(framesPerSecond).IsGreaterThan(0D);
        await Assert.That(model.TotalEvents).IsGreaterThan(0L);
        await Assert.That(model.SourceCount).IsGreaterThan(0);
    }

