    /// <summary>Constructs a paused instance with stable diagnostic timestamps.</summary>
    /// <returns>The owned view model.</returns>
    private static MainWindowViewModel CreatePausedModel()
    {
        var model = new MainWindowViewModel(new FixedTimeProvider());
        model.StartPauseCommand.Execute(null);
        DrainDispatcher();
        return model;
    }

    /// <summary>Processes all queued projection work before the low-priority sentinel.</summary>
    private static void DrainDispatcher()
    {
        var frame = new DispatcherFrame();
        _ = Dispatcher.CurrentDispatcher.BeginInvoke(DispatcherPriority.ApplicationIdle, () => frame.Continue = false);
        Dispatcher.PushFrame(frame);
    }

    /// <summary>Copies a UI-facing non-generic sequence for stable assertions.</summary>
    /// <typeparam name="T">The projected item type.</typeparam>
    /// <param name="items">The dispatcher-owned sequence.</param>
    /// <returns>The projected items in source order.</returns>
    private static T[] ReadItems<T>(System.Collections.IEnumerable items)
    {
        List<T> result = [];
        foreach (T item in items)
        {
            result.Add(item);
        }

        return result.ToArray();
    }
