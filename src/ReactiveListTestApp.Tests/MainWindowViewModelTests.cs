    /// <summary>Publishes pause and resume state together with dependent command notifications.</summary>
    /// <returns>A task representing the asynchronous test.</returns>
    [Test]
    public async Task StartPauseCommand_Toggled_UpdatesStateAndAvailability()
    {
        using var model = new MainWindowViewModel(new FixedTimeProvider());
        List<string?> properties = [];
        model.PropertyChanged += (_, args) => properties.Add(args.PropertyName);
        var notifications = 0;
        model.StepCommand.CanExecuteChanged += (_, _) => notifications++;
        model.StartPauseCommand.Execute(null);
        var pausedStatus = model.StatusText;
        var pausedLabel = model.StartPauseText;
        var pausedOperation = model.LastOperation;
        var pausedCanStep = model.StepCommand.CanExecute(null);
        model.StartPauseCommand.Execute(null);
        var resumedStatus = model.StatusText;
        var resumedOperation = model.LastOperation;
        var resumedCanStep = model.StepCommand.CanExecute(null);
        model.StartPauseCommand.Execute(null);
        await Assert.That(pausedStatus).IsEqualTo("PAUSED · views remain queryable");
        await Assert.That(pausedLabel).IsEqualTo("Resume");
        await Assert.That(pausedOperation).IsEqualTo("Continuous producer paused");
        await Assert.That(pausedCanStep).IsTrue();
        await Assert.That(resumedCanStep).IsFalse();
        await Assert.That(resumedStatus).IsEqualTo("LIVE · worker ingesting full-rate batches");
        await Assert.That(resumedOperation).IsEqualTo("Continuous producer resumed");
        await Assert.That(properties.Contains(nameof(MainWindowViewModel.IsRunning))).IsTrue();
        await Assert.That(properties.Contains(nameof(MainWindowViewModel.StartPauseText))).IsTrue();
        await Assert.That(notifications).IsEqualTo(ToggleCount);
        await Assert.That(model.EventsPerSecond).IsEqualTo(0D);
        await Assert.That(model.UiFramesPerSecond).IsEqualTo(0D);
    }

