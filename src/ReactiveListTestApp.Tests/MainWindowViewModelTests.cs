    /// <summary>Bounds historical tape and diagnostics during repeated manual bursts.</summary>
    /// <returns>A task representing the asynchronous test.</returns>
    [Test]
    public async Task BurstCommand_Repeated_BoundsRetainedCollections()
    {
        using var model = CreatePausedModel();
        model.TargetRate = RawFrameCount;
        for (var i = 0; i < BurstCount; i++)
        {
            model.BurstCommand.Execute(null);
            DrainDispatcher();
        }

        await Assert.That(model.TotalEvents).IsEqualTo((long)BurstCount * RawFrameCount);
        await Assert.That(model.LiveTape.Count).IsEqualTo(TapeLimit);
        await Assert.That(model.SourceCount).IsEqualTo(TapeLimit);
        await Assert.That(model.QuaternaryDictionaryCount).IsEqualTo(InstrumentCount);
        await Assert.That(model.QuaternaryListCount).IsLessThanOrEqualTo(IndexedLimit);
        await Assert.That(ReadItems<StreamEvent>(model.StreamEvents).Length).IsEqualTo(StreamLimit);
        await Assert.That(model.LastOperation.StartsWith("Burst generated 1,000 events", StringComparison.Ordinal)).IsTrue();
    }

